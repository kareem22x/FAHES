/**
 * بوابة الجلسة — القاعدة في مكان واحد.
 *
 * ── لماذا دالة نقيّة لا `if` في كل شاشة ───────────────────────────────────
 *
 * السؤال «هل نعرض الواجهة أم ننتظر أم نطرد إلى الدخول؟» يُسأل في ثلاثة
 * مواضع على الأقل: بوابة الدخول (`app/index.tsx`)، ومجموعة التبويبات
 * (`app/(tabs)/_layout.tsx`)، وقريبًا مجموعة الفاحص (M3). كتابة الشرط في
 * كل موضع تُنتج ثلاث نسخ تتباعد عند أول تعديل — وهو بالضبط ما حدث في
 * الويب مع «ثلاث بوابات لا واحدة».
 *
 * والدالة نقيّة عن قصد: بلا React وبلا حالة، فيمكن اختبارها بلا مُصيّر.
 *
 * ── ⚠️ `loading` قبل كل شيء ───────────────────────────────────────────────
 *
 * Clerk يقرأ الجلسة المحفوظة **بشكل غير متزامن**. أثناء ذلك `isSignedIn`
 * تساوي `false` ولو كان المستخدم مسجّلًا فعلًا. لذلك الترتيب هنا ليس
 * تجميليًّا: لو فحصنا `isSignedIn` قبل `isLoaded` لقذفنا كل مستخدم مسجَّل
 * إلى شاشة الدخول عند كل إقلاع — وهو أكثر خطأ شائع في Clerk على الجوال.
 */
export type SessionGate = 'loading' | 'signed-out' | 'signed-in'

export function sessionGate(isLoaded: boolean, isSignedIn: boolean): SessionGate {
  if (!isLoaded) return 'loading'
  return isSignedIn ? 'signed-in' : 'signed-out'
}
