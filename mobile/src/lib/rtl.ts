import { I18nManager, Platform } from 'react-native'

/**
 * اتجاه الواجهة — من اليمين إلى اليسار.
 *
 * ── لماذا فرضٌ على مستوى المنصّة لا `direction` في الأنماط ────────────────
 *
 * المنتج عربي بالكامل (لا نسخة إنجليزية)، فالـRTL ليس خيارًا يُبدَّل بل حقيقة
 * ثابتة. وإجباره في `I18nManager` يجعل React Native يقلب **كل** `flexDirection:
 * 'row'` تلقائيًّا، و`marginLeft`/`paddingRight` تُقلب معها، ونقطة بداية
 * النصّ تصير اليمين. أما قلب كل نمط يدويًّا فمستحيل عمليًّا: مئات المواضع،
 * وأي واحد يُنسى يظهر معكوسًا على جهاز المستخدم لا على جهازك.
 *
 * ── ⚠️ القيد الذي يجب معرفته ──────────────────────────────────────────────
 *
 * `forceRTL` يُقرأ **عند إقلاع التطبيق فقط**. تغييره وقت التشغيل لا يقلب
 * الواجهة المفتوحة — يلزم إعادة تحميل كاملة. لذلك:
 *
 *   * يُضبط هنا على مستوى الوحدة، قبل رسم أي شاشة.
 *   * في التطوير، أول تشغيل بعد إضافة هذا الملف يقلب الاتجاه فقط بعد إعادة
 *     تحميل واحدة (`r` في طرفية Expo). هذا سلوك المنصّة لا خلل.
 *   * القيمة محفوظة في التخزين الأصلي، فالتشغيلات التالية تُقلع RTL مباشرةً.
 *
 * ── الويب ─────────────────────────────────────────────────────────────────
 *
 * `I18nManager` لا يفعل شيئًا على الويب (`react-native-web` يتجاهله)، والاتجاه
 * هناك يأتي من `dir` في المستند. فبدل ترك الويب LTR — وهو ما يجعل المعاينة
 * **لا تشبه المنتج**: `flexDirection: 'row'` لا يُقلب، فتنفصل نقطة القائمة عن
 * نصّها، و`text-align: start` يصير يسارًا — نضبط `dir="rtl"` هنا.
 *
 * ⚠️ **هذا ليس ترفًا تجميليًّا**: هدف الويب هو الوسيلة الوحيدة لمعاينة الواجهة
 * بلا محاكي، ومعاينة تُظهر اتجاهًا مخالفًا تُخفي أخطاء التخطيط الحقيقية
 * وتُظهر أخطاء وهمية. فبضبطه تصير المعاينة مرآة صادقة للجهاز.
 *
 * و`lang="ar"` معه: يُصلح تشكيل الأرقام واختيار الخط الاحتياطي في المتصفح.
 */
export function enforceRTL(): void {
  if (Platform.OS === 'web') {
    // `document` غير معرَّف في العرض على الخادم (SSR) ⇒ الفحص لازم.
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('dir', 'rtl')
      document.documentElement.setAttribute('lang', 'ar')
    }
    return
  }

  // `allowRTL` قبل `forceRTL`: الثانية بلا الأولى لا تفعل شيئًا على أندرويد.
  I18nManager.allowRTL(true)
  I18nManager.forceRTL(true)
}

/**
 * هل الواجهة تسير من اليمين فعلًا الآن؟
 *
 * تُستخدم للتشخيص فقط: إن أرجعت `false` على جهاز عربي فالتطبيق يحتاج إعادة
 * تحميل واحدة ليقلب. مفيدة في سجل الإقلاع، ولا يبنى عليها أي قرار عرض.
 */
export function isRTLEffective(): boolean {
  if (Platform.OS === 'web') {
    return typeof document !== 'undefined' && document.documentElement.getAttribute('dir') === 'rtl'
  }
  return I18nManager.isRTL
}
