import * as Haptics from 'expo-haptics'
import { Platform } from 'react-native'

/**
 * الهوبتيك — غلاف رقيق حول `expo-haptics`.
 *
 * ── لماذا غلاف لا نداء مباشر ──────────────────────────────────────────────
 *
 * ثلاثة أسباب، كلها ظهرت في مشاريع حقيقية:
 *
 *   1. **الويب**: `expo-haptics` لا يملك محرّكًا على الويب (يعتمد على
 *      `navigator.vibrate` وهو غير مدعوم في iOS Safari). فنداء مباشر من شاشة
 *      تعمل على الويب = رمية قد تُسقط المعالج.
 *   2. **الأجهزة بلا محرّك**: أجهزة لوحية وكثير من الأجهزة الرخيصة لا محرّك
 *      فيها، والوعد يُرفض.
 *   3. **لا يجوز أن يُسقط الاهتزاز إجراءً**: ضغط زرّ «ادفع الآن» يجب أن يمرّ
 *      حتى لو فشل الاهتزاز. لذلك كل نداء هنا **مُبتلَع الخطأ** ولا يُنتظر.
 *
 * ── لماذا لا `await` في مواضع النداء ──────────────────────────────────────
 *
 * الاهتزاز إحساس لا نتيجة. لو انتظرناه لأضفنا إطارًا أو أكثر قبل تنفيذ
 * الإجراء — وهو عكس المطلوب في تطبيق يُلمس مئات المرّات في الجلسة.
 *
 * ── مقياس الاستخدام ───────────────────────────────────────────────────────
 *
 * `tap` للأزرار العادية · `select` لتغيير اختيار (تبويب، خيار قائمة) ·
 * `success`/`warning` لنتيجة عملية. ولا تُستخدم في السحب أو التمرير إطلاقًا:
 * اهتزاز متكرّر أثناء الإيماءة يُشعر الجهاز بالخلل.
 */

const supported = Platform.OS === 'ios' || Platform.OS === 'android'

/** يُشغّل الوعد ويتجاهل نتيجته وفشله معًا. */
function fire(run: () => Promise<void>): void {
  if (!supported) return
  void run().catch(() => {
    /* لا محرّك، أو إذن مرفوض، أو المنصّة لا تدعم — لا شيء يُبلَّغ عنه. */
  })
}

export const haptic = {
  /** ضغطة زرّ عادية. الأخفّ المتاح. */
  tap(): void {
    fire(() => Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light))
  },

  /**
   * تغيير اختيار — تبديل تبويب، اختيار مدينة، تشغيل مفتاح.
   *
   * `selectionAsync` لا `impactAsync`: الأول هو ما خصّصته Apple للاختيار،
   * وهو أقصر وأحدّ من ضغطة عادية.
   */
  select(): void {
    fire(() => Haptics.selectionAsync())
  },

  /** نجاح عملية — إتمام طلب، حفظ تعديل. */
  success(): void {
    fire(() => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success))
  },

  /** تحذير — إجراء غير قابل للتراجع، أو نتيجة تحتاج انتباهًا. */
  warning(): void {
    fire(() => Haptics.notificationAsync(Haptics.NotificationFeedbackType.Warning))
  },
} as const
