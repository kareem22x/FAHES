/**
 * خدمات الفحص — منقولة من قائمة الخادم المُلزِمة.
 *
 * ── مصدر الحقيقة ──────────────────────────────────────────────────────────
 *
 * `app/api/inspections/route.ts` يحمل:
 *
 *     const allowedServices = ['فحص شامل', 'فحص ميكانيكي', 'فحص هيكل وبوية', 'فحص كمبيوتر']
 *
 * وهذا **القيد الفعلي**: أي قيمة خارجها يرفضها الخادم بـ400. والقائمة نفسها
 * مكرّرة أيضًا في `new-request-wizard.tsx` (قائمة اختيار) و`app/help`
 * (نصّ) — أي أن الانحراف بين الويب والتطبيق وارد إن لم يُنقل حرفيًّا.
 *
 * ⚠️ **المعرّف نصّ عربي كما يخزّنه الخادم، ولا يُعاد صياغته ولا يُترجم.**
 * `services` تُخزَّن مصفوفة نصوص في القاعدة وتُقارَن بالقيمة الحرفية؛ تحويلها
 * إلى مفاتيح لاتينية هنا يعني جدول ترجمة رابعًا يتباعد عن الثلاثة.
 *
 * ── الوصف ─────────────────────────────────────────────────────────────────
 *
 * الأوصاف القصيرة منقولة من `new-request-wizard.tsx` (الأسطر 42–45) — نفس
 * النصّ الذي يراه المستخدم على الويب، فلا يقرأ وصفين للخدمة نفسها.
 */

export type InspectionService = {
  /** القيمة الحرفية التي يخزّنها الخادم ويقبلها. */
  readonly id: string
  /** سطر توضيحي واحد — من الويب لا مُخترَع هنا. */
  readonly summary: string
}

export const INSPECTION_SERVICES: readonly InspectionService[] = [
  { id: 'فحص شامل', summary: 'الأنظمة الأساسية في تقرير واحد' },
  { id: 'فحص ميكانيكي', summary: 'المحرك وناقل الحركة والتعليق' },
  { id: 'فحص هيكل وبوية', summary: 'الحوادث والدهان وإصلاحات الهيكل' },
  { id: 'فحص كمبيوتر', summary: 'قراءة أعطال الكمبيوتر وسجل الصيانة' },
] as const

/** الخدمة الافتراضية — مطابقة لافتراضي المعالج على الويب (`['فحص شامل']`). */
export const DEFAULT_INSPECTION_SERVICE = INSPECTION_SERVICES[0].id

/**
 * تبديل خدمة في مجموعة مختارة (اختيار متعدّد).
 *
 * ── لماذا دالّة نقيّة لا `useState` مع `Set` ──────────────────────────────
 *
 * لأن القاعدة «واحدة على الأقل» تُختبَر بلا مُصيّر: المعالج على الويب يسمح
 * بالجمع بين خدمتين، وطلب بلا خدمة واحدة لا معنى له. فالإزالة تُرفض إن كانت
 * الأخيرة — وهذا سلوك يجب أن يُختبر لا أن يُخمَّن.
 *
 * وتُعيد مصفوفة **جديدة** دائمًا: تعديل المصفوفة في مكانها لا يُحدِث رسمًا في
 * React، وهي `react-hooks/immutability` نفسها التي تحرس ذلك.
 */
export function toggleInspectionService(selected: readonly string[], id: string): string[] {
  if (!selected.includes(id)) return [...selected, id]
  // لا تُفرغ القائمة: طلب فحص بلا نوع فحص لا يُقبل على الخادم.
  if (selected.length <= 1) return [...selected]
  return selected.filter((service) => service !== id)
}
